package com.leetcode2.org.动态规划;

import java.util.Arrays;

public class Solution935 {
    // 定义取模的常量值，避免结果过大
    static final int MOD = 1000000007;

    /**
     * 计算长度为 n 的骑士拨号器的所有可能的拨号序列数。
     * @param n 拨号序列的长度
     * @return 有效的拨号序列数（取模 MOD）
     */
    public int knightDialer(int n) {
        // 定义每个数字的可达邻居（骑士跳跃规则）
        int[][] moves = {
                {4, 6},       // 从 0 可以跳到 4 和 6
                {6, 8},       // 从 1 可以跳到 6 和 8
                {7, 9},       // 从 2 可以跳到 7 和 9
                {4, 8},       // 从 3 可以跳到 4 和 8
                {3, 9, 0},    // 从 4 可以跳到 3, 9 和 0
                {},           // 5 是一个无效的数字，无法跳到任何地方
                {1, 7, 0},    // 从 6 可以跳到 1, 7 和 0
                {2, 6},       // 从 7 可以跳到 2 和 6
                {1, 3},       // 从 8 可以跳到 1 和 3
                {2, 4}        // 从 9 可以跳到 2 和 4
        };

        // 定义动态规划数组 d
        // d[0][j] 表示当前步的状态，d[1][j] 表示前一步的状态
        int[][] d = new int[2][10];

        // 初始化第一步（n = 1）的所有数字，设置为 1，因为单个数字本身就是一种拨号序列
        Arrays.fill(d[1], 1);

        // 从第二步开始计算直到第 n 步
        for (int i = 2; i <= n; i++) {
            // x 表示当前步的索引，使用 `i & 1` 来在 0 和 1 之间切换
            int x = i & 1;
            // 遍历所有数字 j
            for (int j = 0; j < 10; j++) {
                // 初始化当前数字 j 的计数为 0
                d[x][j] = 0;
                // 遍历数字 j 所有的可跳跃目标数字 k
                for (int k : moves[j]) {
                    // 更新 dp 值，累加从上一步 k 跳跃到当前步 j 的所有可能性
                    d[x][j] = (d[x][j] + d[x ^ 1][k]) % MOD;
                }
            }
        }

        // 最终结果存储在第 n 步的状态中，累加所有数字的可能性
        int res = 0;
        for (int x : d[n % 2]) {
            res = (res + x) % MOD;
        }
        return res;
    }
}
